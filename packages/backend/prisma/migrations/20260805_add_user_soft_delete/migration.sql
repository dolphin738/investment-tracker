-- ============================================================
-- add_user_soft_delete — 注销账户改为软删除（SET-P1-06）
--
-- 语义：users 表新增 deleted_at 可空列。
-- - NULL       → 正常用户
-- - 非 NULL    → 已注销（软删除），保留 30 天可恢复
-- 软删除期间该用户不能登录（auth.service login 查询排除），
-- 其 email 仍占用唯一索引，避免重注册后与旧数据冲突
-- （仅软删保留期内；30 天后由清理任务硬删整行，索引槽释放，同邮箱可重注册）。
-- ============================================================

ALTER TABLE "users" ADD COLUMN "deleted_at" TIMESTAMP(3);
